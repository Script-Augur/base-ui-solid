/**
 * Present on the select popup element.
 */
export enum SelectPopupDataAttributes {
  /**
   * Present when the corresponding select is open.
   */
  open = 'data-open',
  /**
   * Present when the corresponding select is closed.
   */
  closed = 'data-closed',
  /**
   * Indicates which side the popup is anchored to.
   */
  side = 'data-side',
  /**
   * Indicates how the popup is aligned.
   */
  align = 'data-align',
}
