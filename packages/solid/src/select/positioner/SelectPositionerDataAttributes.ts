/**
 * Present on the select positioner element.
 */
export enum SelectPositionerDataAttributes {
  /**
   * Present when the corresponding select is open.
   */
  open = 'data-open',
  /**
   * Present when the corresponding select is closed.
   */
  closed = 'data-closed',
  /**
   * Indicates which side the positioner is anchored to.
   */
  side = 'data-side',
  /**
   * Indicates how the positioner is aligned.
   */
  align = 'data-align',
}
