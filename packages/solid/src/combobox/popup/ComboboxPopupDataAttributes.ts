/**
 * Present on the combobox popup element.
 */
export enum ComboboxPopupDataAttributes {
  /**
   * Present when the corresponding combobox is open.
   */
  open = 'data-open',
  /**
   * Present when the corresponding combobox is closed.
   */
  closed = 'data-closed',
  /**
   * Indicates which side the popup is anchored to.
   */
  side = 'data-side',
  /**
   * Indicates how the popup is aligned.
   */
  align = 'data-align',
}
