/**
 * Present on the combobox positioner element.
 */
export enum ComboboxPositionerDataAttributes {
  /**
   * Present when the corresponding combobox is open.
   */
  open = 'data-open',
  /**
   * Present when the corresponding combobox is closed.
   */
  closed = 'data-closed',
  /**
   * Indicates which side the positioner is anchored to.
   */
  side = 'data-side',
  /**
   * Indicates how the positioner is aligned.
   */
  align = 'data-align',
}
