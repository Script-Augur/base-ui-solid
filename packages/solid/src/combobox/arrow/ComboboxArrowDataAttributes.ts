/**
 * Present on the combobox arrow element.
 */
export enum ComboboxArrowDataAttributes {
  /**
   * Present when the anchor is partially or fully hidden.
   */
  anchorHidden = 'data-anchor-hidden',
  /**
   * Present when the arrow is uncentered relative to the anchor.
   */
  uncentered = 'data-uncentered',
}
